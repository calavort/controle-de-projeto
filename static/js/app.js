function parseProjectDate(value){
  const text = String(value || '').trim();
  if(!text) return null;
  const iso = text.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if(iso) return new Date(Number(iso[1]), Number(iso[2]) - 1, Number(iso[3]));
  const br = text.match(/^(\d{2})\/(\d{2})\/(\d{4})/);
  if(br) return new Date(Number(br[3]), Number(br[2]) - 1, Number(br[1]));
  const parsed = new Date(text);
  return Number.isNaN(parsed.getTime()) ? null : new Date(parsed.getFullYear(), parsed.getMonth(), parsed.getDate());
}

function formatDateTimeShort(value){
  const text = String(value || '').trim();
  if(!text) return '-';
  let date = null;
  const iso = text.match(/^(\d{4})-(\d{2})-(\d{2})(?:[T\s](\d{2}):(\d{2}))?/);
  if(iso){
    date = new Date(Number(iso[1]), Number(iso[2]) - 1, Number(iso[3]), Number(iso[4] || 0), Number(iso[5] || 0));
  }else{
    const br = text.match(/^(\d{2})[\/-](\d{2})[\/-](\d{4})(?:[T\s](\d{2}):(\d{2}))?/);
    if(br) date = new Date(Number(br[3]), Number(br[2]) - 1, Number(br[1]), Number(br[4] || 0), Number(br[5] || 0));
  }
  if(!date || Number.isNaN(date.getTime())) return text;
  const pad = value => String(value).padStart(2, '0');
  return `${pad(date.getDate())}-${pad(date.getMonth() + 1)}-${date.getFullYear()} / ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

