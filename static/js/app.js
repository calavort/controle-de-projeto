function futureCompletionDate(payload){
  if(payload.status !== 'Concluído' || !payload.due_date) return null;
  const due = parseProjectDate(payload.due_date);
  const today = parseProjectDate(todayIsoDate());
  return due && today && due > today ? due : null;
}

async function confirmFutureCompletedProject(payload){
  const futureDate = futureCompletionDate(payload);
  if(!futureDate) return true;
  return confirmAction({
    title: 'Data de entrega futura',
    message: `A data de entrega informada (${formatDateOnly(payload.due_date)}) é posterior à data atual. O projeto está sendo registrado como concluído. Deseja continuar com o cadastro?`,
    confirmText: 'Continuar'
  });
}

function validateProjectDateOrder(payload){
  const start = parseProjectDate(payload.start_date);
  const due = parseProjectDate(payload.due_date);
  if(!start || !due || start <= due) return true;
  syncProjectDateConstraints();
  showToast('A data de início não pode ser posterior à data de término.');
  $('[data-project-field="start_date"]')?.focus();
  return false;
}

async function saveReferenceProject(event){
  event.preventDefault();
  const payload = projectPayloadFromReferenceForm();
  if(!payload.code || !payload.title){
    showToast('Informe código e título do projeto.');
    return;
  }
  if(!validateProjectDateOrder(payload)) return;
  if(!validateCompletedRevisionHistory()) return;
  if(!(await confirmFutureCompletedProject(payload))) return;

  if(state.editingProjectId){
    const original = (state.data?.projects || []).find(item => Number(item.id) === Number(state.editingProjectId));
    const changedProgram = original && payload.program !== (original.program || '');
    const changedMode = original && payload.stage_mode !== (original.stage_mode || '');
    let regenerated = false;
    if(changedProgram || changedMode){
      const confirmed = await confirmAction({
        title: 'Trocar etapas do projeto',
        message: `Você alterou o fluxo para ${payload.program} · ${payload.stage_mode}. Isso vai substituir as etapas atuais pelo modelo desse programa/nível e o progresso atual das etapas será perdido. Confirmar?`,
        confirmText: 'Substituir etapas'
      });
      if(confirmed){
        payload.regenerate_stages = true;
        regenerated = true;
      }else{
        payload.program = original.program || payload.program;
        payload.stage_mode = original.stage_mode || payload.stage_mode;
      }
    }
    await api(`/api/projects/${state.editingProjectId}`, {method: 'PUT', body: payload});
    showToast(regenerated ? 'Projeto atualizado e etapas regeneradas.' : 'Projeto atualizado.');
  }else{
    await api('/api/projects', {method: 'POST', body: payload});
    showToast('Projeto salvo com sucesso.');
  }
  state.editingProjectId = null;
  state.descriptionAutoGenerated = false;
  await loadState();
  openView('projects');
}

