async function finalizeProject(){
  const project = activeProject();
  if(!project?.id){
    showToast('Nenhum projeto ativo.');
    return;
  }
  const confirmed = await confirmAction({
    title: 'Finalizar projeto',
    message: `Concluir "${project.code || 'o projeto'}" e lançar na planilha de controle de tramitação?`,
    confirmText: 'Finalizar'
  });
  if(!confirmed) return;
  showToast('Finalizando e lançando na planilha...');
  const result = await api(`/api/projects/${project.id}/finalize`, {method: 'POST'});
  await loadState();
  const report = result?.spreadsheet || {};
  const messages = [];
  if(report.error){
    messages.push(`Projeto concluído, mas a planilha não foi preenchida: ${report.error}`);
  }else if(report.written > 0){
    messages.push('Projeto concluído e lançado na planilha.');
  }else if((report.skipped || []).length){
    messages.push('Projeto concluído. A linha já existia na planilha (não duplicada).');
  }else{
    messages.push('Projeto concluído.');
  }
  (report.warnings || []).forEach(warning => messages.push(warning));
  (report.skipped || []).forEach(skip => messages.push(skip));
  if(messages.length > 1){
    await confirmAction({title: 'Finalização concluída', message: messages.join('\n\n'), confirmText: 'Entendi'});
  }else{
    showToast(messages[0]);
  }
}

