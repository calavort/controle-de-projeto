function updateStageEditorTotal(){
  const total = $$('#stageEditorList .stage-weight').reduce((sum, input) => sum + (Number(input.value) || 0), 0);
  const label = $('#stageEditorTotal');
  const over = total > 100.000001;
  if(label){
    label.textContent = Number.isInteger(total) ? String(total) : total.toFixed(1);
    label.classList.toggle('stage-editor-total-high', over);
  }
  const warn = $('#stageEditorWarn');
  if(warn) warn.classList.toggle('show', over);
}

