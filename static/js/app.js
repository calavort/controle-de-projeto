async function submitReopenStages(){
  const project = activeProject();
  if(!project?.id) return showToast('Nenhum projeto ativo.');
  const stageOrders = Array.from(state.reopenStageOrders).sort((a, b) => a - b);
  if(!stageOrders.length) return showToast('Selecione ao menos uma etapa.');
  await api(`/api/projects/${project.id}/stages/reopen`, {
    method: 'POST',
    body: {stage_orders: stageOrders}
  });
  resetReopenStages();
  await loadState();
  showToast(stageOrders.length === 1 ? 'Etapa reaberta.' : 'Etapas reabertas.');
}

