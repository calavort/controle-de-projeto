function referenceStep(stage, project = null, stages = []){
  const percent = Number(stage.internal_percent || 0);
  const done = stageDone(stage);
  const current = !done && (stage.status === 'Em andamento' || percent > 0);
  const automaticDetail = isDetailProgressStage(stage);
  const cls = done ? 'done' : current ? 'current' : '';
  const seconds = stageDisplaySeconds(stage);
  const doneDate = formatDateDashOnly(stage.completed_at || stage.updated_at || '');
  const percentText = automaticDetail ? percent.toLocaleString('pt-BR', {maximumFractionDigits: 1}) : percent.toFixed(0);
  const statusMeta = done
    ? ['Concluída', formatStageHours(seconds), doneDate !== '-' ? doneDate : ''].filter(Boolean).join(' - ')
    : current ? `Em andamento · ${percentText}%` : stage.status || 'Aguardando';
  const timePercent = Number(stage.time_percent || 0);
  const timeMeta = !done && seconds > 0 ? `Tempo real ${formatSeconds(seconds)}${timePercent > 0 ? ` (${timePercent.toFixed(0)}%)` : ''}` : '';
  const meta = [statusMeta, timeMeta].filter(Boolean).join(' · ');
  const order = Number(stage.stage_order || 0);
  let action = '';
  if(reopenModeActive(project)){
    const checked = state.reopenStageOrders.has(order) ? 'checked' : '';
    const disabled = canReopenStage(stage, project) ? '' : 'disabled';
    const title = disabled ? 'Apenas etapas concluídas podem ser reabertas' : 'Selecionar etapa';
    action = `
      <label class="stage-reopen-control ${disabled}" title="${escapeHtml(title)}">
        <input type="checkbox" data-stage-reopen-check="${order}" ${checked} ${disabled} />
      </label>
    `;
  }else if(!done && activeProject()?.id){
    // Mesmo a etapa de detalhamento (concluída automaticamente pelo Progresso de
    // detalhamento) exibe o botão Concluir manual. O backend mantém a conclusão
    // manual (manual_confirmed) e não a sobrescreve pela sincronização automática.
    action = `<button type="button" class="mini-action stage-complete-action" data-stage-complete="${order}">Concluir</button>`;
  }
  return `
    <li class="step ${cls}">
      <div class="step-mark" aria-hidden="true"></div>
      <div><div class="step-name">${escapeHtml(stage.name)}</div><div class="step-meta">${escapeHtml(meta)}</div></div>
      ${action}
    </li>
  `;
}

