function parentDirectoryPath(value, treatAsFile = false){
  const text = String(value || '').trim().replace(/[\\/]+$/, '');
  if(!text) return '';
  const separator = text.includes('\\') ? '\\' : '/';
  const parts = text.split(/[\\/]+/);
  if(parts.length <= 1) return text;
  if(treatAsFile || parts.length > 1) parts.pop();
  if(!parts.length) return '';
  const prefix = /^[A-Za-z]:/.test(parts[0]) ? `${parts.shift()}${separator}` : (text.startsWith(separator) ? separator : '');
  return prefix + parts.join(separator);
}

function lastLocationInitialDir(kind){
  const settings = state.data?.settings || {};
  if(kind === 'model') return settings.last_model_parent || parentDirectoryPath(settings.last_model_path || '');
  if(kind === 'documents') return settings.last_document_parent || parentDirectoryPath(settings.last_document_folder || '');
  if(kind === 'spreadsheet') return settings.last_spreadsheet_parent || parentDirectoryPath(settings.last_spreadsheet_path || '', true);
  return '';
}

