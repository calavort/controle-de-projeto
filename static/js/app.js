function escapeHtml(value){
  return String(value ?? '').replace(/[&<>"']/g, char => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[char]));
}

function settingEnabled(key, defaultValue = true){
  const value = state.data?.settings?.[key];
  if(value === undefined || value === null || value === '') return defaultValue;
  if(typeof value === 'boolean') return value;
  return !['0', 'false', 'não', 'nao', 'off'].includes(String(value).trim().toLocaleLowerCase('pt-BR'));
}

async function api(path, options = {}){
  const request = {
    headers: {'Content-Type': 'application/json'},
    ...options
  };
  if(request.body && typeof request.body !== 'string'){
    request.body = JSON.stringify(request.body);
  }
  const response = await fetch(path, request);
  const payload = await response.json().catch(() => ({}));
  if(!response.ok || payload.ok === false){
    throw new Error(payload.message || 'Falha na operação.');
  }
  return payload.data ?? payload;
}

function showToast(message){
  const toast = $('#toast');
  if(!toast) return;
  toast.textContent = message;
  toast.classList.add('show');
  clearTimeout(state.toastTimer);
  state.toastTimer = setTimeout(() => toast.classList.remove('show'), 2600);
}

