async function loadState({silent = false} = {}){
  if(state.loading) return state.data;
  state.loading = true;
  try{
    state.data = await api('/api/state');
    const projects = state.data?.projects || [];
    const availableIds = new Set(projects.map(project => Number(project.id)));
    if(!availableIds.has(Number(state.indicatorProjectId || 0))){
      state.indicatorProjectId = Number(state.data?.active_project?.id || projects[0]?.id || 0) || null;
    }
    if(state.indicatorProjectId){
      const active = state.data?.active_project || null;
      if(Number(active?.id || 0) === Number(state.indicatorProjectId)){
        state.indicatorProject = active;
      }else{
        state.indicatorProject = await api(`/api/projects/${state.indicatorProjectId}`);
      }
    }else{
      state.indicatorProject = null;
    }
    renderAll();
    return state.data;
  }catch(error){
    if(!silent) throw error;
    return state.data;
  }finally{
    state.loading = false;
  }
}

