function openStageTimeAdjuster(){
  const project = activeProject();
  if(!project?.id){
    showToast('Nenhum projeto ativo.');
    return;
  }
  const stages = project.stages || [];
  if(!stages.length){
    showToast('Nenhuma etapa cadastrada.');
    return;
  }
  const dialog = ensureStageTimeAdjustDialog();
  $('#stageTimeAdjustSub', dialog).textContent = `${project.code || ''} · ajuste manual dos tempos exibidos por etapa.`;
  $('#stageTimeAdjustList', dialog).innerHTML = stages.map(stage => {
    const order = Number(stage.stage_order || 0);
    const seconds = stageDisplaySeconds(stage);
    const duration = secondsToHoursMinutes(seconds);
    const status = stage.status || (stageDone(stage) ? 'Concluída' : 'Não iniciada');
    return `
      <div class="stage-adjust-row" data-stage-adjust-row data-stage-order="${order}">
        <span class="stage-editor-idx">${order}.</span>
        <div class="stage-adjust-title">
          <strong>${escapeHtml(stage.name || `Etapa ${order}`)}</strong>
          <small>${escapeHtml(status)} · atual ${escapeHtml(formatSeconds(seconds))}</small>
        </div>
        <input type="number" min="0" step="1" data-stage-adjust-hours aria-label="Horas da etapa ${order}" value="${duration.hours}">
        <input type="number" min="0" step="1" data-stage-adjust-minutes aria-label="Minutos da etapa ${order}" value="${duration.minutes}">
      </div>
    `;
  }).join('');
  updateStageTimeAdjustTotal();
  dialog.hidden = false;
}

function collectStageTimeAdjustments(){
  const dialog = $('#stageTimeAdjustDialog');
  return $$('[data-stage-adjust-row]', dialog).map(row => {
    const hours = durationInputValue($('[data-stage-adjust-hours]', row));
    const minutes = durationInputValue($('[data-stage-adjust-minutes]', row));
    return {
      stage_order: Number(row.dataset.stageOrder || 0),
      seconds: Math.round((hours * 3600) + (minutes * 60))
    };
  }).filter(item => item.stage_order > 0);
}

function updateStageTimeAdjustTotal(){
  const total = collectStageTimeAdjustments().reduce((sum, item) => sum + item.seconds, 0);
  const label = $('#stageTimeAdjustTotal');
  if(label) label.textContent = formatSeconds(total);
}

async function saveStageTimeAdjustments(){
  const project = activeProject();
  if(!project?.id) return showToast('Nenhum projeto ativo.');
  const stages = collectStageTimeAdjustments();
  if(!stages.length) return showToast('Nenhuma etapa para ajustar.');
  await api(`/api/projects/${project.id}/stage-times`, {
    method: 'PUT',
    body: {stages}
  });
  const dialog = $('#stageTimeAdjustDialog');
  if(dialog) dialog.hidden = true;
  await loadState();
  showToast('Tempo das etapas ajustado.');
}

