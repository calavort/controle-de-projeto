async function completeStage(stageOrder){
  const project = activeProject();
  if(!project?.id) return showToast('Nenhum projeto ativo.');
  const plan = await api(`/api/projects/${project.id}/stages/${stageOrder}/completion-plan`);
  let timeDistributionOrders = null;
  if(plan?.out_of_order){
    timeDistributionOrders = await chooseStageTimeDistribution(plan);
    if(!timeDistributionOrders) return;
  }
  const body = {
    status: 'Concluída',
    internal_percent: 100,
    manual_confirmed: true,
    message: 'Etapa concluída.'
  };
  if(Array.isArray(timeDistributionOrders)) body.time_distribution_orders = timeDistributionOrders;
  await api(`/api/projects/${project.id}/stages/${stageOrder}`, {
    method: 'PATCH',
    body
  });
  await loadState();
  showToast(plan?.out_of_order ? 'Etapa concluída e tempo registrado.' : 'Etapa concluída.');
}

