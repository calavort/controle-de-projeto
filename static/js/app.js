function validateCompletedRevisionHistory(){
  if(($('[data-project-field="status"]')?.value || '') !== 'Concluído') return true;
  const history = collectCompletedRevisionHistory();
  const seen = new Set();
  for(const item of history){
    if(!item.revision || !item.revision_date){
      showToast('Informe a revisão e a respectiva data.');
      return false;
    }
    const key = item.revision.toLocaleLowerCase('pt-BR');
    if(seen.has(key)){
      showToast(`A revisão ${item.revision} foi informada mais de uma vez.`);
      return false;
    }
    seen.add(key);
  }
  return true;
}

