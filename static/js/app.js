function revisionDateInputValue(value){
  const text = String(value || '').trim();
  const iso = text.match(/^(\d{4}-\d{2}-\d{2})/);
  if(iso) return iso[1];
  const br = text.match(/^(\d{2})[/-](\d{2})[/-](\d{4})/);
  return br ? `${br[3]}-${br[2]}-${br[1]}` : '';
}

