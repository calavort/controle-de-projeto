function ensureRevisionRowsForCurrent(){
  const status = $('[data-project-field="status"]')?.value || '';
  if(status !== 'Concluído') return;
  const currentRevision = String($('[data-project-field="revision"]')?.value || '0').trim() || '0';
  const existing = new Set(
    completedRevisionRows().map(row => $('[data-revision-number]', row)?.value.trim()).filter(Boolean)
  );
  const targets = /^\d+$/.test(currentRevision) && Number(currentRevision) <= 50
    ? Array.from({length: Number(currentRevision) + 1}, (_, index) => String(index))
    : [currentRevision];
  targets.forEach(revision => {
    if(existing.has(revision)) return;
    addCompletedRevisionRow({
      revision,
      revision_date: revision === currentRevision ? ($('[data-project-field="due_date"]')?.value || '') : ''
    });
    existing.add(revision);
  });
}

function renderCompletedRevisionHistory(project = null){
  const list = $('#completedRevisionRows');
  if(!list) return;
  list.innerHTML = '';
  const history = Array.isArray(project?.revisions) ? [...project.revisions] : [];
  history.sort((a, b) => {
    const av = String(a.revision || '');
    const bv = String(b.revision || '');
    if(/^\d+$/.test(av) && /^\d+$/.test(bv)) return Number(av) - Number(bv);
    return av.localeCompare(bv, 'pt-BR', {numeric: true, sensitivity: 'base'});
  });
  history.forEach(addCompletedRevisionRow);
  ensureRevisionRowsForCurrent();
  refreshCompletedRevisionEmptyState();
}

