function normalizedFirstWord(value){
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase('pt-BR')
    .match(/[a-z0-9]+/)?.[0] || '';
}

function buildAutomaticDescription(title){
  let cleanTitle = String(title || '').trim();
  if(!cleanTitle) return '';
  cleanTitle = cleanTitle.replace(/[.!?]+\s*$/, '').trim();

  const explicitArticles = [
    [/^os\s+/i, 'dos'],
    [/^as\s+/i, 'das'],
    [/^o\s+/i, 'do'],
    [/^a\s+/i, 'da']
  ];
  let connector = 'de';
  for(const [pattern, contraction] of explicitArticles){
    if(pattern.test(cleanTitle)){
      cleanTitle = cleanTitle.replace(pattern, '').trim();
      connector = contraction;
      break;
    }
  }

  if(connector === 'de'){
    const first = normalizedFirstWord(cleanTitle);
    const masculineSingular = new Set([
      'suporte', 'projeto', 'desenho', 'croqui', 'modelo', 'conjunto',
      'detalhe', 'sistema', 'transportador', 'guarda-corpo'
    ]);
    const feminineSingular = new Set([
      'plataforma', 'estrutura', 'escada', 'lista', 'tubulacao', 'linha',
      'unidade', 'area', 'passarela', 'base', 'chapa', 'fabricacao'
    ]);
    const masculinePlural = new Set([
      'suportes', 'projetos', 'desenhos', 'croquis', 'modelos', 'conjuntos',
      'detalhes', 'sistemas', 'transportadores', 'guarda-corpos'
    ]);
    const femininePlural = new Set([
      'plataformas', 'estruturas', 'escadas', 'listas', 'tubulacoes', 'linhas',
      'unidades', 'areas', 'passarelas', 'bases', 'chapas'
    ]);
    if(masculineSingular.has(first)) connector = 'do';
    else if(feminineSingular.has(first)) connector = 'da';
    else if(masculinePlural.has(first)) connector = 'dos';
    else if(femininePlural.has(first)) connector = 'das';
  }

  return `Detalhamento ${connector} ${cleanTitle}.`;
}

