function projectRevisionDate(project){
  const currentRevision = String(project?.revision || '0').trim() || '0';
  if(!project || !currentRevision || currentRevision === '0') return null;
  const revisions = Array.isArray(project?.revisions) ? project.revisions : [];
  const exact = revisions.find(item => String(item?.revision || '').trim() === currentRevision);
  const anyRevision = revisions.find(item => String(item?.revision || '').trim() && String(item?.revision || '').trim() !== '0');
  return parseProjectDate(exact?.revision_date || exact?.created_at || anyRevision?.revision_date || anyRevision?.created_at);
}

function projectMonthGroups(projects, unfinishedLabel = 'Projetos'){
  const unfinished = [];
  const undatedCompleted = [];
  const monthly = new Map();
  (projects || []).forEach(project => {
    const date = projectCompletionDate(project);
    const completed = projectDisplayStatus(project) === 'Concluído' || progressValue(project) >= 100;
    if(!completed){
      unfinished.push(project);
      return;
    }
    if(!date){
      undatedCompleted.push(project);
      return;
    }
    const key = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`;
    if(!monthly.has(key)) monthly.set(key, {date, projects: []});
    monthly.get(key).projects.push(project);
  });
  const groups = [];
  if(unfinished.length){
    groups.push({key: 'unfinished', label: unfinishedLabel, projects: unfinished});
  }
  [...monthly.entries()]
    .sort((a, b) => b[0].localeCompare(a[0]))
    .forEach(([key, group]) => {
      const label = group.date.toLocaleDateString('pt-BR', {month: 'long', year: 'numeric'});
      groups.push({key, label: label.charAt(0).toUpperCase() + label.slice(1), projects: group.projects});
    });
  if(undatedCompleted.length){
    groups.push({key: 'completed-undated', label: 'Concluídos sem data registrada', projects: undatedCompleted});
  }
  return groups;
}

