function suggestedNextRevision(){
  const values = completedRevisionRows()
    .map(row => $('[data-revision-number]', row)?.value.trim())
    .filter(Boolean);
  const current = $('[data-project-field="revision"]')?.value.trim();
  if(current) values.push(current);
  const numeric = values.filter(value => /^\d+$/.test(value)).map(Number);
  if(numeric.length) return String(Math.max(...numeric) + 1);
  const letters = values.filter(value => /^[A-Z]$/i.test(value)).map(value => value.toUpperCase().charCodeAt(0));
  if(letters.length) return String.fromCharCode(Math.max(...letters) + 1);
  return current || '0';
}

