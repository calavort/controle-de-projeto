function setupProjectSuggestionFields(){
  $$('[data-project-suggestion]').forEach(input => {
    if(input.dataset.suggestionReady === '1') return;
    input.dataset.suggestionReady = '1';
    const control = input.closest('.project-suggestion-control');
    const toggle = control?.querySelector('.project-suggestion-toggle');
    const menu = control?.querySelector('.project-suggestion-menu');
    input.setAttribute('role', 'combobox');
    input.setAttribute('aria-autocomplete', 'list');
    input.setAttribute('aria-expanded', 'false');
    input.addEventListener('focus', () => openProjectSuggestionMenu(input));
    input.addEventListener('input', () => openProjectSuggestionMenu(input));
    input.addEventListener('keydown', event => {
      if(event.key === 'Escape'){
        closeProjectSuggestionMenus();
        return;
      }
      if(event.key === 'ArrowDown'){
        event.preventDefault();
        if(menu?.hidden) openProjectSuggestionMenu(input, {showAll: true});
        const options = $$('.project-suggestion-option', menu);
        const active = $('.project-suggestion-option.active', menu);
        const index = active ? options.indexOf(active) : -1;
        options.forEach(option => option.classList.remove('active'));
        options[Math.min(index + 1, options.length - 1)]?.classList.add('active');
        return;
      }
      if(event.key === 'ArrowUp'){
        event.preventDefault();
        const options = $$('.project-suggestion-option', menu);
        const active = $('.project-suggestion-option.active', menu);
        const index = active ? options.indexOf(active) : options.length;
        options.forEach(option => option.classList.remove('active'));
        options[Math.max(index - 1, 0)]?.classList.add('active');
        return;
      }
      if(event.key === 'Enter'){
        const active = $('.project-suggestion-option.active', menu);
        if(active){
          event.preventDefault();
          selectProjectSuggestion(input, active.dataset.suggestionValue);
        }
      }
    });
    toggle?.addEventListener('click', event => {
      event.preventDefault();
      event.stopPropagation();
      if(menu && !menu.hidden) closeProjectSuggestionMenus();
      else openProjectSuggestionMenu(input, {showAll: true});
    });
    menu?.addEventListener('mousedown', event => event.preventDefault());
    menu?.addEventListener('click', event => {
      const option = event.target.closest('[data-suggestion-value]');
      if(option) selectProjectSuggestion(input, option.dataset.suggestionValue);
    });
  });
}

